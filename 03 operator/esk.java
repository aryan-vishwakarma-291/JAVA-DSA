        a += 10;   // a = a + 10 
        System.out.println(a);

        a -= 10;  // a = a - 10
        System.out.println(a);

        a *= 10;  // a = a*10
        System.out.println(a);

        a /= 10;  // a = a/10
        System.out.println(a);



